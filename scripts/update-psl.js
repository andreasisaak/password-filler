#!/usr/bin/env node
/**
 * Regenerate mac/Agent/PublicSuffixListRules.swift from the official
 * Public Suffix List (ICANN + PRIVATE sections), or check its age.
 *
 * Invocation:
 *   node scripts/update-psl.js                  # download + regenerate
 *   node scripts/update-psl.js --check-age 30   # fail if older than 30 days
 *
 * Rules are normalised to the form browsers send hostnames in: lowercase,
 * IDN labels in Punycode (WHATWG `domainToASCII`, the same mapping Chrome
 * and Firefox apply), split into plain, wildcard and exception rules;
 * `PublicSuffixList.swift` turns each list into a set at first use. Run
 * before a release and commit the regenerated file; the release workflow
 * runs the age check.
 */

'use strict';

const fs = require('fs');
const path = require('path');
const { domainToASCII } = require('url');

const PSL_URL = 'https://publicsuffix.org/list/public_suffix_list.dat';
const OUTPUT_PATH = path.join(__dirname, '..', 'mac', 'Agent', 'PublicSuffixListRules.swift');
const RELATIVE_OUTPUT_PATH = path.relative(path.join(__dirname, '..'), OUTPUT_PATH);
// Written by `renderSwift`, read back by `checkAge`.
const VERSION_HEADER = '// PSL version: ';
// The list has held well over 9000 rules for years; fewer means a truncated
// or wrong download, and shipping it would weaken host matching.
const MINIMUM_RULE_COUNT = 9000;
const NORMALISED_DOMAIN = /^[a-z0-9-]+(\.[a-z0-9-]+)*$/;
const USAGE = 'Usage: node scripts/update-psl.js [--check-age <days>]';

function parseArgs(argv) {
  const args = argv.slice(2);
  if (args.length === 0) return { checkAgeDays: null };
  if (args.length === 2 && args[0] === '--check-age' && /^\d+$/.test(args[1])) {
    return { checkAgeDays: Number(args[1]) };
  }
  throw new Error(`Unexpected arguments "${args.join(' ')}". ${USAGE}`);
}

function headerValue(text, key) {
  const match = text.match(new RegExp(`^// ${key}: (\\S+)$`, 'm'));
  if (!match) {
    throw new Error(`PSL header line "// ${key}: …" not found in ${PSL_URL}`);
  }
  return match[1];
}

function toASCII(rawRule, domain) {
  const ascii = domainToASCII(domain);
  if (ascii === '' || !NORMALISED_DOMAIN.test(ascii)) {
    throw new Error(`PSL rule "${rawRule}" normalised to "${ascii}", expected ${NORMALISED_DOMAIN}`);
  }
  return ascii;
}

// Splits the rules by kind so the Swift side only builds sets:
// `!www.ck` → exceptions `www.ck`, `*.ck` → wildcardParents `ck`, rest → suffixes.
function parseRules(text) {
  const rules = { suffixes: new Set(), wildcardParents: new Set(), exceptions: new Set() };
  for (const line of text.split('\n')) {
    // Per the PSL format, a rule ends at the first whitespace.
    const rawRule = line.trim().split(/\s/)[0];
    if (rawRule === '' || rawRule.startsWith('//')) continue;

    if (rawRule.startsWith('!')) {
      rules.exceptions.add(toASCII(rawRule, rawRule.slice(1)));
    } else if (rawRule.startsWith('*.')) {
      rules.wildcardParents.add(toASCII(rawRule, rawRule.slice(2)));
    } else {
      rules.suffixes.add(toASCII(rawRule, rawRule));
    }
  }
  return rules;
}

function ruleCount(rules) {
  return rules.suffixes.size + rules.wildcardParents.size + rules.exceptions.size;
}

function renderList(name, values) {
  return [`    static let ${name} = #"""`, ...values, '"""#'];
}

function renderSwift(rules, version, commit) {
  return [
    '// Generated by scripts/update-psl.js. Do not edit by hand.',
    `// Source: ${PSL_URL}`,
    `${VERSION_HEADER}${version}`,
    `// PSL commit: ${commit}`,
    `// Rules: ${ruleCount(rules)} (ICANN + PRIVATE sections, IDN labels in Punycode)`,
    '',
    'enum PublicSuffixListRules {',
    ...renderList('suffixes', rules.suffixes),
    ...renderList('wildcardParents', rules.wildcardParents),
    ...renderList('exceptions', rules.exceptions),
    '}',
    '',
  ].join('\n');
}

// A hosting platform missing from a stale list lets its tenants fill each
// other's credentials, so releases refuse a list older than `maxAgeDays`.
function checkAge(maxAgeDays) {
  const generated = fs.readFileSync(OUTPUT_PATH, 'utf8');
  const line = generated.split('\n').find((candidate) => candidate.startsWith(VERSION_HEADER));
  const date = line?.slice(VERSION_HEADER.length).match(/^(\d{4}-\d{2}-\d{2})_/)?.[1];
  if (!date) {
    throw new Error(`No "${VERSION_HEADER}YYYY-MM-DD_…" header in ${RELATIVE_OUTPUT_PATH}; run node scripts/update-psl.js`);
  }

  const ageDays = Math.floor((Date.now() - Date.parse(`${date}T00:00:00Z`)) / 86_400_000);
  if (ageDays > maxAgeDays) {
    throw new Error(
      `Public Suffix List is ${ageDays} days old (version ${date}, limit ${maxAgeDays}). `
      + `Run node scripts/update-psl.js, commit ${RELATIVE_OUTPUT_PATH}, then tag again.`);
  }
  console.log(`Public Suffix List version ${date} is ${ageDays} days old (limit ${maxAgeDays})`);
}

async function regenerate() {
  console.log(`Fetching ${PSL_URL}`);
  const response = await fetch(PSL_URL);
  if (!response.ok) {
    throw new Error(`PSL download failed: HTTP ${response.status} ${response.statusText} from ${PSL_URL}`);
  }
  const text = await response.text();

  const version = headerValue(text, 'VERSION');
  const commit = headerValue(text, 'COMMIT');
  const rules = parseRules(text);
  const count = ruleCount(rules);
  if (count < MINIMUM_RULE_COUNT) {
    throw new Error(`PSL has ${count} rules, expected at least ${MINIMUM_RULE_COUNT}; refusing to write ${RELATIVE_OUTPUT_PATH}`);
  }

  fs.writeFileSync(OUTPUT_PATH, renderSwift(rules, version, commit));
  console.log(`Wrote ${count} rules (PSL version ${version}) to ${RELATIVE_OUTPUT_PATH}`);
}

async function main() {
  const { checkAgeDays } = parseArgs(process.argv);
  if (checkAgeDays === null) {
    await regenerate();
  } else {
    checkAge(checkAgeDays);
  }
}

main().catch((error) => {
  console.error(error.message);
  process.exit(1);
});
